using System.Collections;
using System.Text;
using System.Text.RegularExpressions;

namespace TplCore.Compiler;

public class Generator
{
    #region Declaration

    private static string OpenBlockNamePrefix = "<!--";
    private static string BlockNameSuffix = "-->";
    private static string CloseBlockNamePrefix = "<!--/";

    private static string TagPrefix = "{";
    private static string TagSuffix = "}";
    private static string StaticStringPrefix = "static:";
    private static string LoadStringPrefix = "load:";
    private static string DefaultValueIndicator = ":";


    /*  In tag name
     *  Use exactly static naming for auto-located value
     *  Ex: {static:Resources.Lang.lblUserName} will be compiled to Resources.Lang.lblUserName in template object
     */

    public readonly string TemplateName;
    private int StringCounter;
    private int TagCounter;
    private const int cz = 1000;

    private static string BlockVariablePrefix = "";
    private static string TagVariablePrefix = "t";
    private static string StringVariablePrefix = "s";

    // Use 2 hashtable to resolve duplicated block name
    private static Hashtable BlockNames;
    private static Hashtable BlockVariables;

    private string NameSpaceName;
        
    #endregion

    public Generator(string templateName, string nameSpaceName)
    {
        NameSpaceName = ToNamespaceName(nameSpaceName);
        TemplateName = ToNamespaceName(templateName);

        BlockNames = new Hashtable();
        BlockVariables = new Hashtable();
    }

    #region Header and Footer

    private string OpenTemplate()
    {
        return "\t\tpublic class " + TemplateName + TplSettings.TemplateSuffix + " : Template\r\n\t\t{\r\n";
    }

    private string OpenTemplate_NS()
    {
        var builder = new StringBuilder(200);
        builder.Append("// <auto-generated />\r\n");
        builder.Append("#region!!!This file is auto-generated by TplBuilder, don't modify it manually!!!\r\n");
        builder.Append("using System;\r\nusing System.Text;\r\nusing TplCore.Element;\r\n");
        builder.Append("#pragma warning disable\r\n");

        builder.Append("namespace " + NameSpaceName.Replace('_', '.') + "\r\n{\r\n\t");

        builder.Append("//{\r\n");

        return builder.ToString();
    }

    private static string CloseTemplate()
    {
        return "\r\n\t\t}\r\n\r\n";
    }

    private static string CloseTemplate_NS()
    {
        return "\t//}\r\n}\r\n#pragma warning enable\r\n#endregion";
    }

    private static string OpenBlock(string name)
    {
        if (BlockNames.ContainsKey(name))
        {
            var i = (int)BlockNames[name] + 1;
            BlockNames[name] = i;
            return "\t\tpublic class " + name + i + TplSettings.BlocSuffix + ": Block\r\n\t\t{\r\n";
        }

        BlockNames.Add(name, 0);
        return "\t\tpublic class " + name + TplSettings.BlocSuffix + ": Block\r\n\t\t{\r\n";
    }

    private static string CloseBlock()
    {
        return "\t\t}\r\n\r\n";
    }

    #endregion

    #region Searching

    private List<object> SplitBlock(string text) // First level only
    {
        if (string.IsNullOrEmpty(text))
        {
            return null;
        }

        List<object> objects = [];

        // Open Block
        var i1 = text.IndexOf(OpenBlockNamePrefix);
        if (-1 == i1)
        {
            objects.Add(new NonBlockChunk(text));
            return objects;
        }

        var i2 = text.IndexOf(BlockNameSuffix, i1);
        if (-1 == i2)
        {
            objects.Add(new NonBlockChunk(text));
            return objects;
        }

        var start = i1 + OpenBlockNamePrefix.Length;
        var length = i2 - start;

        var name = text.Substring(start, length);

        // Close Block
        var j1 = text.IndexOf(CloseBlockNamePrefix + name + BlockNameSuffix, i2);
        if (-1 == j1)
        {
            objects.Add(new NonBlockChunk(text));
            return objects;
        }

        // Check Block name is valid
        if (IsBlockName(name))
        {
            start = i1 + OpenBlockNamePrefix.Length + name.Length + BlockNameSuffix.Length;
            length = j1 - start;

            var beginner = text.Substring(0, i1);
            objects.Add(new NonBlockChunk(beginner));

            name = ToPropertyName(name);
            var content = text.Substring(start, length);
            objects.Add(new BlockChunk(name, content));

            var ender = text.Substring(j1 + CloseBlockNamePrefix.Length + name.Length + BlockNameSuffix.Length);
            List<object> objects1 = SplitBlock(ender);

            if (null != objects1)
            {
                objects.AddRange(objects1);
            }
        }
        else
        {
            objects.Add(new NonBlockChunk(text));
        }

        return objects;
    }

    private object[] FindFirstTag(string text, int index = 0)
    {
        if (string.IsNullOrEmpty(text))
        {
            return null;
        }

        var i1 = text.IndexOf(TagPrefix, index);
        if (-1 == i1)
        {
            return null;
        }

        var i2 = text.IndexOf(TagSuffix, i1 + TagPrefix.Length);
        if (-1 == i2)
        {
            return null;
        }

        var start = i1 + TagPrefix.Length;
        var length = i2 - start;

        var name = text.Substring(start, length);

        if (IsTagName(name))
        {
            var beginner = text.Substring(0, i1);
            var ender = text.Substring(i1 + TagPrefix.Length + name.Length + TagSuffix.Length);

            return [beginner, name, ender];
        }

        return FindFirstTag(text, i1 + 1);
    }

    #endregion

    public string RenderTemplate(string text)
    {
        if (string.IsNullOrEmpty(text))
        {
            return null;
        }

        Filtering.FilterTemplate(ref text);

        List<string> LTag = [];
        var builder = new StringBuilder(cz);

        builder.Append(OpenTemplate_NS());
        builder.Append(RenderBlock(text, TemplateName, ref LTag));
        builder.Append(CloseTemplate_NS());

        return builder.ToString();
    }



    #region Render Block

    private string RenderBlock(string text, string parentName, ref List<string> LTag)
    {
        List<object> objects = SplitBlock(text);
        var builder = new StringBuilder(cz);
        if (null == objects)
        {
            builder.Append(OpenBlock(parentName));
            builder.Append(RenderToStringMethod(ref LTag, null, null, parentName == TemplateName));
            builder.Append(CloseBlock());
            return builder.ToString();
        }
        var c = objects.Count;

        // Open
        builder.Append(parentName == TemplateName ? OpenTemplate() : OpenBlock(parentName));

        List<string> fields = [];
        var isObjects = new List<bool?>();

        var bHasChildBlock = false;
        var ChildBlockIdxs = new List<int>();
        for (var i = 0; i < c; i++)
        {
            var obj = objects[i];
            if (obj is NonBlockChunk chunk)
            {
                // Append String and tag
                builder.Append(RenderNonBlock(chunk.Content, ref LTag, ref fields, ref isObjects));
            }
            else
            {
                bHasChildBlock = true;
                ChildBlockIdxs.Add(i);
                // Append declaration of new Block
                var block = (BlockChunk)obj;
                builder.Append(DeclareBlockVariable(block.Name, parentName, ref fields, ref isObjects));
            }
        }

        // Render ToString method
        builder.Append(RenderToStringMethod(ref LTag, fields, isObjects, parentName == TemplateName));

        // Close
        builder.Append(parentName == TemplateName ? CloseTemplate() : CloseBlock());

        // Render next child Block
        if (bHasChildBlock)
        {
            c = ChildBlockIdxs.Count;
            for (var i = 0; i < c; i++)
            {
                var obj = objects[ChildBlockIdxs[i]];
                var block = (BlockChunk)obj;
                List<string> lTag = [];

                builder.Append(RenderBlock(block.Content, parentName + TplSettings.Separator + block.Name, ref lTag));
            }
        }

        return builder.ToString();
    }

    // Non-block contains tag and String, no child Block
    private string RenderNonBlock(string text, ref List<string> LTag, ref List<string> fields, ref List<bool?> isObjects)
    {
        if (string.IsNullOrEmpty(text))
        {
            return null;
        }

        var builder = new StringBuilder(1000);

        object[] bs = FindFirstTag(text);
        if (null == bs)
        {
            builder.Append(RenderString(text, ref fields, ref isObjects)); // Wow! Great!
        }
        else
        { // No problem, recursive loop it

            // Render String
            builder.Append(RenderString((string)bs[0], ref fields, ref isObjects));

            // Render tag
            builder.Append(RenderTag((string)bs[1], ref LTag, ref fields, ref isObjects));

            // Render non-block child
            builder.Append(RenderNonBlock((string)bs[2], ref LTag, ref fields, ref isObjects));
        }

        return builder.ToString();
    }

    private static string DeclareBlockVariable(string name, string parentName, ref List<string> fields, ref List<bool?> isObjects)
    {
        var p = parentName + TplSettings.Separator + name;

        if (BlockVariables.ContainsKey(p))
        {
            var i = (int)BlockVariables[p] + 1;
            BlockVariables[p] = i;

            fields.Add(BlockVariablePrefix + name + i);
            isObjects.Add(true);

            return "\t\t\tpublic " + p + i + TplSettings.BlocSuffix + " " + fields[fields.Count - 1] + " = new " + p + i + TplSettings.BlocSuffix + "();\r\n";
        }

        BlockVariables.Add(p, 0);

        fields.Add(BlockVariablePrefix + name);
        isObjects.Add(true);

        return "\t\t\tpublic " + p + TplSettings.BlocSuffix + " " + fields[fields.Count - 1] + " = new " + p + TplSettings.BlocSuffix + "();\r\n";
    }


    #endregion

    private string RenderTag(string name, ref List<string> LTag, ref List<string> fields, ref List<bool?> isObjects)
    {
        if (LTag.Contains(ToPropertyName(name)))
        { // Render reference to existed tag

            fields.Add(TagVariablePrefix + TagCounter++ + TplSettings.Separator + ToPropertyName(name));
            isObjects.Add(null);

            return "\t\t\tprotected string " + fields[fields.Count - 1] + ";\r\n";
        }  // Add and render new tag

        if (name.Contains(StaticStringPrefix)) // Static tag
        {
            fields.Add(StringVariablePrefix + StringCounter++);
            isObjects.Add(false);
            LTag.Add(fields[fields.Count - 1]);

            return "\t\t\tprotected static string " + fields[fields.Count - 1] + "{get{return " + name.Remove(0, StaticStringPrefix.Length) + ";}}\r\n";
        }

        if (name.Contains(LoadStringPrefix))//{load:IBC.Agent.UI.Template1 template1 = new IBC.Agent.UI.Template1()}
        {
            var var = string.Empty;
            var declaration = RenderChild(name, ref var);

            fields.Add(var);
            isObjects.Add(false);
            LTag.Add(fields[fields.Count - 1]);

            return declaration;
        }

        if (name.Contains(DefaultValueIndicator))
        {
            string[] args = name.Split([DefaultValueIndicator], StringSplitOptions.None);

            var defaultValue = args[1];
            name = ToPropertyName(args[0]);

            fields.Add(name);
            isObjects.Add(false);
            LTag.Add(name);

            return "\t\t\tpublic string " + fields[fields.Count - 1] + " = \"" + defaultValue + "\";\r\n";

        }

        name = ToPropertyName(name);

        fields.Add(name);
        isObjects.Add(false);
        LTag.Add(name);

        return "\t\t\tpublic string " + fields[fields.Count - 1] + " = \"{" + name + "}\";\r\n";
    }

    private string RenderString(string text, ref List<string> fields, ref List<bool?> isObjects)
    {
        // Remove all double white spaces
        text = Regex.Replace(text, "\\s{2,}", string.Empty);
        if (string.IsNullOrEmpty(text))
        {
            return null;
        }

        fields.Add(StringVariablePrefix + StringCounter++);
        isObjects.Add(false);

        return "\t\t\tprotected static string " + fields[fields.Count - 1] + " = \"" + text.Replace("\"", "\\\"") + "\";\r\n";
    }

    #region Child Template

    private string RenderChild(string command, ref string name)
    {
        command = command.Remove(0, LoadStringPrefix.Length);
        var i1 = command.IndexOf(' ');
        var i2 = command.IndexOf('=');

        if (i1 == -1 || i2 == -1)
        {
            return null;
        }

        name = command.Substring(i1, i2 - i1).Trim();

        var privateName = "_" + name;
        var type = command.Substring(0, i1);
        var initial = command.Substring(i2 + 1);

        var publicMethod = "\t\t\tpublic " + type + " " + name + "{get {return " + privateName + " != null ? " + privateName + " : " + privateName + " = " + initial + ";}}\r\n";
        var privateDeclare = "\t\t\tprotected " + type + " " + privateName + ";\r\n";

        return publicMethod + privateDeclare;
    }

    #endregion

    #region ToString method

    private string OpenToString1Method()
    {
        return "\t\t\tpublic string ToString()\r\n\t\t\t{\r\n";
    }

    private static string CloseToStringMethod()
    {
        return "\t\t\t}\r\n";
    }

    private static string OpenToStringMethod()
    {
        return "\t\t\tpublic override void ToString(ref StringBuilder bd)\r\n\t\t\t{\r\n";
    }

    private string RenderToStringMethod(ref List<string> LTag, List<string> fields, List<bool?> isObjects, bool isTemplateClass) // ToString with StringBuilder param
    {
        var bd = new StringBuilder(500);
        int c;
        if (null == fields || (c = fields.Count) == 0)
        {
            bd.Append(OpenToStringMethod());

            bd.Append("\t\t\t\tif(IsAssigned){bd.Append(Value);}\r\n");

            bd.Append(CloseToStringMethod());

            if (isTemplateClass)
            {
                bd.Append(RenderToString1Method());
            }

            return bd.ToString();
        }

        bd.Append(OpenToStringMethod());

        bd.Append("\t\t\t\tif(!Visible) return;\r\n");


        bd.Append("\t\t\t\tif(RenderChild)\r\n\t\t\t\t{\r\n");
        const string tab = "\t\t\t\t\t";

        for (var i = 0; i < c; i++)
        {
            if (isObjects[i] == true)
            {
                bd.Append(tab + "if(null != " + fields[i] + ") " + fields[i] + ".ToString(ref bd);\r\n");
            }
            else
            {
                var name = fields[i];
                var j = name.IndexOf(TplSettings.Separator);
                if (isObjects[i] == null && -1 != j && LTag.Contains(name = name.Remove(0, j + TplSettings.Separator.Length)))
                {
                    bd.Append(tab + "bd.Append(" + name + ");\r\n");
                }
                else
                {
                    bd.Append(tab + "bd.Append(" + fields[i] + ");\r\n");
                }
            }
        }



        bd.Append("\t\t\t\t}\r\n");
        bd.Append("\t\t\t\tif(IsAssigned){bd.Append(Value);}\r\n");

        bd.Append(CloseToStringMethod());

        if (isTemplateClass)
        {
            bd.Append(RenderToString1Method());
        }

        return bd.ToString();
    }

    private string RenderToString1Method() // ToString with no param
    {
        var bd = new StringBuilder(100);
        bd.Append(OpenToString1Method());

        bd.Append("\t\t\t\tStringBuilder bd = new StringBuilder();\r\n");

        bd.Append("\t\t\t\tToString(ref bd);\r\n");

        bd.Append("\t\t\t\treturn bd.ToString();\r\n");
        bd.Append(CloseToStringMethod());

        return bd.ToString();
    }


    #endregion

    #region Concatenation

    private static string ToPropertyName(string name)
    {
        return name.Replace('-', '_'); // !!! Note: Do not make the length changed
    }

    private static string ToNamespaceName(string name)
    {
        return name.Replace('-', '_').Replace('.', '_').Replace(' ', '_');
        // !!! Note: Do not make the length changed
    }

    #endregion

    #region Validation

    private static bool IsBlockName(string name)
    {
        return Regex.IsMatch(name, "^[A-Za-z0-9_\\-]+$");
    }

    private static bool IsTagName(string name)
    {
        return Regex.IsMatch(name, "^[^\r\n\t]+$");
    }

    #endregion
}

#region DataElement

internal struct NonBlockChunk(string content)
{
    public string Content = content;
}

internal struct BlockChunk(string name, string content)
{
    public string Name = name;
    public string Content = content;
}

#endregion